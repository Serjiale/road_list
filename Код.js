function встановитиGoogleClientId() {
  const ui = SpreadsheetApp.getUi();
  const поточний = PropertiesService.getScriptProperties().getProperty('GOOGLE_CLIENT_ID');
  const відповідь = ui.prompt(
    'Google Client ID',
    (поточний ? 'Вже встановлено (перезапишеться новим). ' : '') +
    'Встав Client ID з Google Cloud Console (Credentials → OAuth 2.0 Client ID):',
    ui.ButtonSet.OK_CANCEL
  );
  if (відповідь.getSelectedButton() === ui.Button.OK) {
    const id = відповідь.getResponseText().trim();
    if (id) {
      PropertiesService.getScriptProperties().setProperty('GOOGLE_CLIENT_ID', id);
      ui.alert('Збережено.');
    }
  }
}

