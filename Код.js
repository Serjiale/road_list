function створитиАркуш_(ss, назва, заголовки) {
  let аркуш = ss.getSheetByName(назва);
  if (!аркуш) аркуш = ss.insertSheet(назва);
  аркуш.clear();
  аркуш.getRange(1, 1, 1, заголовки.length).setValues([заголовки])
    .setFontWeight('bold').setBackground('#4a86c8').setFontColor('#ffffff');
  аркуш.setFrozenRows(1);
  аркуш.autoResizeColumns(1, заголовки.length);
  return аркуш;
}

function додатиВипадаючийСписок_(аркуш, колонка, варіанти) {
  const правило = SpreadsheetApp.newDataValidation().requireValueInList(варіанти, true).build();
  аркуш.getRange(2, колонка, 500, 1).setDataValidation(правило);
}

// Ставить заголовок конкретної колонки, якщо він ще не такий — і більше нічого не чіпає.
// Безпечний спосіб додати нову колонку в уже існуючий (і вже заповнений даними) аркуш, на
// відміну від ініціалізуватиСистему(), яка б стерла весь аркуш.
function забезпечитиКолонку_(аркуш, номерКолонки, назва) {
  const поточна = аркуш.getRange(1, номерКолонки).getValue();
  if (поточна !== назва) {
    аркуш.getRange(1, номерКолонки).setValue(назва)
      .setFontWeight('bold').setBackground('#4a86c8').setFontColor('#ffffff');
  }
}

// Випадаючий список, джерело якого — жива колонка іншого аркуша (напр. "Підрозділи"), а не
// статичний масив варіантів. Нові підрозділи/водії одразу зʼявляються у списку без правок коду.
function додатиВипадаючийСписокЗДжерела_(аркуш, колонка, діапазонДжерела) {
  const правило = SpreadsheetApp.newDataValidation().requireValueInRange(діапазонДжерела, true).setAllowInvalid(true).build();
  аркуш.getRange(2, колонка, 500, 1).setDataValidation(правило);
}

// Недеструктивно переконується, що аркуші/колонки для підрозділів існують — викликається на
// кожен запит (дешево: кілька getRange/getValue), нічого наявного НІКОЛИ не видаляє й не чистить.
function забезпечитиСтруктуруПідрозділів_() {
  const ss = SpreadsheetApp.getActiveSpreadsheet();

  let аркушПідрозділів = ss.getSheetByName(АРКУШІ.ПІДРОЗДІЛИ);
  if (!аркушПідрозділів) {
    аркушПідрозділів = ss.insertSheet(АРКУШІ.ПІДРОЗДІЛИ);
    забезпечитиКолонку_(аркушПідрозділів, 1, 'Назва');
    аркушПідрозділів.setFrozenRows(1);
  }

  let аркушКористувачів = ss.getSheetByName(АРКУШІ.КОРИСТУВАЧІ);
  if (!аркушКористувачів) {
    аркушКористувачів = ss.insertSheet(АРКУШІ.КОРИСТУВАЧІ);
    забезпечитиКолонку_(аркушКористувачів, 1, 'Email');
    забезпечитиКолонку_(аркушКористувачів, 2, 'Роль');
    забезпечитиКолонку_(аркушКористувачів, 3, 'Підрозділ');
    аркушКористувачів.setFrozenRows(1);
    додатиВипадаючийСписок_(аркушКористувачів, 2, ['Адмін', 'Учасник']);
  }
  додатиВипадаючийСписокЗДжерела_(аркушКористувачів, 3, аркушПідрозділів.getRange('A2:A'));

  const аркушМашин = ss.getSheetByName(АРКУШІ.МАШИНИ);
  забезпечитиКолонку_(аркушМашин, 8, 'Підрозділ');
  забезпечитиКолонку_(аркушМашин, 9, 'Закріплений водій');
  додатиВипадаючийСписокЗДжерела_(аркушМашин, 8, аркушПідрозділів.getRange('A2:A'));
  const аркушВодіїв = ss.getSheetByName(АРКУШІ.ВОДІЇ);
  додатиВипадаючийСписокЗДжерела_(аркушМашин, 9, аркушВодіїв.getRange('A2:A'));
  забезпечитиКолонку_(аркушВодіїв, 2, 'Підрозділ');
  додатиВипадаючийСписокЗДжерела_(аркушВодіїв, 2, аркушПідрозділів.getRange('A2:A'));
}

function видалитиАркуш1_(ss) {
  const дефолтний = ss.getSheetByName('Sheet1') || ss.getSheetByName('Аркуш1');
  if (дефолтний && ss.getSheets().length > 1) ss.deleteSheet(дефолтний);
}

// ==================== ДОВІДКОВІ ДАНІ ДЛЯ ФОРМИ ====================
function отриматиДовідники(користувач) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  return {
    машиниДеталі: зчитатиМашиниДеталі_(ss, користувач),
    водії: зчитатиВодіївДеталі_(ss),
    роль: користувач.роль,
    підрозділ: користувач.підрозділ
  };
}

// Повний список водіїв з їхнім підрозділом — фронтенд сам відфільтровує спливаючий список
// "Водій" під підрозділ обраної машини (колонка 2, "Підрозділ", той самий довідник Підрозділи).
function зчитатиВодіївДеталі_(ss) {
  const аркуш = ss.getSheetByName(АРКУШІ.ВОДІЇ);
  if (!аркуш || аркуш.getLastRow() < 2) return [];
  const дані = аркуш.getRange(2, 1, аркуш.getLastRow() - 1, 2).getValues();
  return дані.filter(р => р[0]).map(р => ({ піб: р[0], підрозділ: р[1] || '' }));
}

// Для Адміна — усі активні машини; для звичайного учасника — тільки ті, що належать його
// підрозділу (колонка 8, "Підрозділ").
function зчитатиМашиниДеталі_(ss, користувач) {
  const аркуш = ss.getSheetByName(АРКУШІ.МАШИНИ);
  if (!аркуш || аркуш.getLastRow() < 2) return [];
  const дані = аркуш.getRange(2, 1, аркуш.getLastRow() - 1, 9).getValues();
  return дані
    .filter(р => !р[6] || р[6] === 'Активний')
    .filter(р => р[0])
    .filter(р => користувач.роль === 'Адмін' || String(р[7] || '').trim() === String(користувач.підрозділ || '').trim())
    .map(р => ({
      держНомер: р[0], марка: р[1], групаЕксплуатації: р[2],
      нормаПалива: р[3], нормаAdBlue: р[4], нормаОливи: р[5],
      підрозділ: р[7] || '', закріпленийВодій: р[8] || ''
    }));
}

// ==================== СТВОРЕННЯ ДОРОЖНЬОГО ЛИСТА ====================
function створитиДорожнійЛист(дані, користувач) {
  if (дані.держНомер) перевіритиДоступДоМашини_(користувач, дані.держНомер);
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.ДОРОЖНІ_ЛИСТИ);

  const рядокЗначень = [
    дані.номерДокумента,
    дані.дата ? new Date(дані.дата) : '',
    дані.дійснийДо || '',
    дані.держНомер, дані.водій, дані.підстава || '', 'Відкритий', дані.одометр || '',
    дані.датаСтворення || new Date(),
    дані.частина || '', дані.старшийМашини || '', дані.начальник || '',
    дані.технікПіб || '', дані.технікДата || '', дані.ктпПіб || '', дані.ктпДата || '',
    дані.причіп || '', дані.причіпНомер || '', дані.вантаж || '', дані.масаВантажу || '',
    дані.вибуттяДата || '', дані.прибуттяДата || '', дані.прибуттяОдометр || ''
  ];

  const останнійРядок = аркуш.getLastRow();
  if (останнійРядок > 1) {
    const номериКолонка = аркуш.getRange(2, 1, останнійРядок - 1, 1).getValues();
    const індекс = номериКолонка.findIndex(р => String(р[0]).trim() === String(дані.номерДокумента).trim());
    if (індекс !== -1) {
      // Захисне оновлення: якщо нове значення порожнє, а старе вже було заповнене — лишаємо старе.
      const поточний = аркуш.getRange(індекс + 2, 1, 1, 23).getValues()[0];
      const обʼєднаний = рядокЗначень.map((зн, i) => {
        if (i === 6) return поточний[6] || 'Відкритий';
        if (i === 8) return поточний[8] || зн;
        return (зн !== '' && зн != null) ? зн : поточний[i];
      });
      аркуш.getRange(індекс + 2, 1, 1, обʼєднаний.length).setValues([обʼєднаний]);
      return { успіх: true };
    }
  }

  аркуш.appendRow(рядокЗначень);
  return { успіх: true };
}

// ==================== НАВІГАЦІЯ ПО ПІДРОЗДІЛАХ (тулбар → машини → її листи) ====================
// Список назв підрозділів — джерело для випадаючого меню в тулбарі (реально користується лише
// Адмін; учасник бачить лише назву свого підрозділу без списку, і без цієї дії).
function отриматиПідрозділи() {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.ПІДРОЗДІЛИ);
  if (аркуш.getLastRow() < 2) return [];
  return аркуш.getRange(2, 1, аркуш.getLastRow() - 1, 1).getValues().map(р => р[0]).filter(String);
}

// Машини конкретного підрозділу (картки зліва). Учаснику підрозділ підміняється на його власний,
// незалежно від того, що він запитав, — так само надійно, як і серверні перевіркиДоступу_ вище.
function отриматиМашиниПідрозділу(підрозділ, користувач) {
  const цільовийПідрозділ = користувач.роль === 'Адмін' ? підрозділ : користувач.підрозділ;
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.МАШИНИ);
  if (аркуш.getLastRow() < 2) return [];
  const дані = аркуш.getRange(2, 1, аркуш.getLastRow() - 1, 9).getValues();
  return дані
    .filter(р => р[0] && (!р[6] || р[6] === 'Активний'))
    .filter(р => String(р[7] || '').trim() === String(цільовийПідрозділ || '').trim())
    .map(р => ({
      держНомер: р[0], марка: р[1], групаЕксплуатації: р[2],
      нормаПалива: р[3], нормаAdBlue: р[4], нормаОливи: р[5],
      підрозділ: р[7] || '', закріпленийВодій: р[8] || ''
    }));
}

// Усі дорожні листи конкретної машини — найсвіжіші (за "Дата документа") зверху.
function отриматиЛистиМашини(держНомер, користувач) {
  перевіритиДоступДоМашини_(користувач, держНомер);
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.ДОРОЖНІ_ЛИСТИ);
  if (аркуш.getLastRow() < 2) return [];
  const дані = аркуш.getRange(2, 1, аркуш.getLastRow() - 1, 9).getValues();
  return дані
    .filter(р => р[0] && String(р[3]).trim() === String(держНомер).trim())
    .sort((a, b) => new Date(b[1]) - new Date(a[1]))
    .map(р => ({ номер: р[0], дата: р[1], водій: р[4], статус: р[6] }));
}

// Місяці в родовому відмінку — той самий порядок і написання, що й у випадаючому списку
// "Дійсний до"/"Технік дата"/"КТП дата" на фронтенді (МІСЯЦІ_РОД у index.html). Шапка листа
// зберігає ці дати як текст "д|м|р" (бо на формі це три окремі select, а не одна дата), тому
// парсимо вручну, щоб перетворити на справжню Date для перенесення в наступний лист.
const МІСЯЦІ_РОД_ = ['січня','лютого','березня','квітня','травня','червня','липня','серпня','вересня','жовтня','листопада','грудня'];
function розпарситиДатуДМР_(текст) {
  const частини = String(текст || '').split('|');
  const день = Number(частини[0]);
  const місяцьІндекс = МІСЯЦІ_РОД_.indexOf(частини[1]);
  const рік = Number(частини[2]);
  if (!день || місяцьІндекс === -1 || !рік) return null;
  const дата = new Date(2000 + рік, місяцьІндекс, день);
  return isNaN(дата.getTime()) ? null : дата;
}

// Дані для передзаповнення НОВОГО листа при створенні з картки машини — логічне продовження
// НАЙСВІЖІШОГО (за "Дата документа") листа цієї машини:
//  - "Дата документа" нового = "Дійсний до" старого (верхній лівий кут бланка) + 1 день (новий
//    лист починається наступного дня); "Дійсний до" нового навмисно НЕ підставляється — вписується
//    вручну.
//  - "Показники одометра: Вибуття" нового = "Показники одометра: Прибуття" старого (кінцевий
//    результат попереднього рейсу стає стартовим для наступного). Дата/час вибуття й прибуття
//    нового листа не підставляються — їх заповнюють водії самостійно.
// Вимагає, щоб найсвіжіший лист машини вже був ЗАКРИТИЙ — інакше кидає помилку (спершу закрий
// поточний). Нічого не зберігає — лише повертає підказку для форми.
function отриматиДаніДляНовогоЛистаМашини(держНомер, користувач) {
  перевіритиДоступДоМашини_(користувач, держНомер);
  const ss = SpreadsheetApp.getActiveSpreadsheet();

  const аркушМашин = ss.getSheetByName(АРКУШІ.МАШИНИ);
  const даніМашин = аркушМашин.getRange(2, 1, аркушМашин.getLastRow() - 1, 9).getValues();
  const машина = даніМашин.find(р => String(р[0]).trim() === String(держНомер).trim());

  const результат = { водій: машина ? (машина[8] || '') : '', вибуттяОдометр: '', датаДокумента: '', пммРядки: [] };

  const аркушЛистів = ss.getSheetByName(АРКУШІ.ДОРОЖНІ_ЛИСТИ);
  if (аркушЛистів.getLastRow() < 2) return результат;
  const даніЛистів = аркушЛистів.getRange(2, 1, аркушЛистів.getLastRow() - 1, 23).getValues();
  const листиМашини = даніЛистів.filter(р => р[0] && String(р[3]).trim() === String(держНомер).trim());
  if (!листиМашини.length) return результат;

  листиМашини.sort((a, b) => new Date(b[1]) - new Date(a[1]));
  const останній = листиМашини[0];
  if (String(останній[6]) !== 'Закритий') {
    throw new Error('Спершу закрий поточний дорожній лист №' + останній[0] + ' цієї машини — новий можна створити лише після закриття попереднього.');
  }
  const номерОстаннього = останній[0];
  const дійснийДоСтарого = останній[2];
  const прибуттяОдометр = останній[22];

  результат.вибуттяОдометр = прибуттяОдометр || '';
  // Новий лист починається НАСТУПНОГО дня після того, як закінчилась дія "Дійсний до" старого.
  const дата = розпарситиДатуДМР_(дійснийДоСтарого);
  if (дата) {
    дата.setDate(дата.getDate() + 1);
    результат.датаДокумента = дата;
  }

  const аркушПММ = ss.getSheetByName(АРКУШІ.ПММ_ЗАПИСИ);
  if (аркушПММ.getLastRow() > 1) {
    const даніПММ = аркушПММ.getRange(2, 1, аркушПММ.getLastRow() - 1, 13).getValues();
    результат.пммРядки = даніПММ
      .filter(р => String(р[1]).trim() === String(номерОстаннього).trim() && Number(р[7]) > 0)
      .map(р => ({ найменування: р[2], тип: р[3], наявність: р[7] }));
  }

  return результат;
}

// Перемикає "Статус" листа (Відкритий/Закритий). Не чіпає жодних інших полів.
function закритиЛист(номерЛиста, закрито, користувач) {
  перевіритиДоступДоЛиста_(користувач, номерЛиста);
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.ДОРОЖНІ_ЛИСТИ);
  const останнійРядок = аркуш.getLastRow();
  if (останнійРядок > 1) {
    const номериКолонка = аркуш.getRange(2, 1, останнійРядок - 1, 1).getValues();
    const індекс = номериКолонка.findIndex(р => String(р[0]).trim() === String(номерЛиста).trim());
    if (індекс !== -1) {
      const новийСтатус = закрито ? 'Закритий' : 'Відкритий';
      аркуш.getRange(індекс + 2, 7).setValue(новийСтатус);
      return { успіх: true, статус: новийСтатус };
    }
  }
  throw new Error('Дорожній лист не знайдено');
}

// ==================== ГЕОКОДУВАННЯ ТА ВІДСТАНІ ====================
// encodeURIComponent() навмисно НЕ екранує апостроф (' лишається "unreserved" за старим
// стандартом ECMA-262) — а Apps Script's UrlFetchApp відмовляється виконувати URL із таким
// сирим апострофом усередині ("Недійсна адреса"). Українські назви населених пунктів регулярно
// містять апостроф (Слов'янськ, Кам'янець-Подільський), тож довкодовуємо його вручну.
function кодуватиURI_(текст) {
  return encodeURIComponent(текст).replace(/'/g, '%27');
}

function отриматиORSКлюч_() {
  const ключ = PropertiesService.getScriptProperties().getProperty('ORS_API_KEY');
  if (!ключ) throw new Error('ORS API ключ не встановлено. Меню "Дорожні листи" → "Встановити ORS API ключ".');
  return ключ;
}

function отриматиКоординати_(назва, біасКоор) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.НАСЕЛЕНІ_ПУНКТИ);
  const дані = аркуш.getLastRow() > 1 ? аркуш.getRange(2, 1, аркуш.getLastRow() - 1, 5).getValues() : [];
  const знайдено = дані.find(р => р[0] && р[0].toString().trim().toLowerCase() === назва.trim().toLowerCase());
  if (знайдено && знайдено[3] && знайдено[4]) {
    if (знайдено[1]) {
      return { lat: знайдено[3], lon: знайдено[4], нове: false, категорія: знайдено[1], довжинаПроїзду: знайдено[2] };
    }
    return { lat: знайдено[3], lon: знайдено[4], нове: true, межі: отриматиМежіПункту_(назва) };
  }

  const ключ = отриматиORSКлюч_();
  let url = 'https://api.openrouteservice.org/geocode/search?api_key=' + encodeURIComponent(ключ) +
    '&text=' + кодуватиURI_(назва + ', Україна') + '&boundary.country=UKR&size=1';
  // Якщо відома координата попереднього пункту маршруту — підказуємо геокодеру шукати ближче до неї,
  // і додатково жорстко обмежуємо пошук радіусом 100 км навколо неї. Це вирішує проблему однойменних
  // населених пунктів у різних областях (напр. кілька "Маліївка", одна з яких за ~150 км). Свідомо НЕ
  // робимо запасний пошук без обмеження радіусом — це раніше просто мовчки підставляло неправильну,
  // зате "популярнішу" глобально точку. Краще чесна помилка з проханням вписати вручну.
  if (біасКоор) {
    url += '&focus.point.lat=' + біасКоор.lat + '&focus.point.lon=' + біасКоор.lon;
    url += '&boundary.circle.lat=' + біасКоор.lat + '&boundary.circle.lon=' + біасКоор.lon + '&boundary.circle.radius=100';
  }
  const відповідь = fetchЗПовтором_(url, { muteHttpExceptions: true });

  const код = відповідь.getResponseCode();
  const текстВідповіді = відповідь.getContentText();
  if (код !== 200) {
    throw new Error(`OpenRouteService (геокодування) відповів кодом ${код} для "${назва}" навіть після кількох ` +
      `повторних спроб. Можна вписати координати пункту вручну в аркуш "Населені пункти" (Широта/Довгота). ` +
      `Деталі: ${текстВідповіді.substring(0, 150)}`);
  }

  const результат = JSON.parse(текстВідповіді);
  if (результат.features && результат.features.length) {
    const [lon, lat] = результат.features[0].geometry.coordinates;
    return { lat: lat, lon: lon, нове: true, межі: отриматиМежіПункту_(назва) };
  }

  // ORS нічого не знайшов у радіусі — пробуємо Nominatim (інша база/індексація, той самий OSM)
  const запаснийРезультат = геокодуватиNominatim_(назва, біасКоор);
  if (запаснийРезультат) {
    return { lat: запаснийРезультат.lat, lon: запаснийРезультат.lon, нове: true, межі: отриматиМежіПункту_(назва) };
  }

  if (біасКоор) {
    // Геокодування повністю провалилось (ні ORS, ні Nominatim), але є приблизна точка відліку
    // (попередній пункт маршруту) — замість "чесної помилки" пропонуємо водієві самому поставити
    // мітку на карті поруч із цією точкою, а не змушуємо лізти редагувати таблицю вручну.
    const е = new Error('НЕ_ЗНАЙДЕНО_РУЧНЕ_РОЗМІЩЕННЯ');
    е.приблизнаКоор = { lat: біасКоор.lat, lon: біасКоор.lon };
    throw е;
  }
  throw new Error('Населений пункт "' + назва + '" не знайдено ні через ORS, ні через Nominatim, і немає жодної ' +
    'точки відліку (це перший пункт маршруту). Впиши координати вручну в аркуш "Населені пункти".');
}

// Запасний геокодер через Nominatim (окрема база/індексація від ORS, хоч і те саме джерело OSM —
// іноді знаходить те, чого не знайшов ORS). Обмежуємо приблизним квадратом ~100км навколо біасу,
// щоб не підхопити однойменний населений пункт деінде.
function геокодуватиNominatim_(назва, біасКоор) {
  try {
    Utilities.sleep(1000);
    let url = 'https://nominatim.openstreetmap.org/search?format=jsonv2&limit=1&q=' +
      кодуватиURI_(назва + ', Україна');
    if (біасКоор) {
      const дельтаШирота = 0.9; // ~100км
      const дельтаДовгота = 0.9 / Math.cos(біасКоор.lat * Math.PI / 180);
      const west = біасКоор.lon - дельтаДовгота, east = біасКоор.lon + дельтаДовгота;
      const south = біасКоор.lat - дельтаШирота, north = біасКоор.lat + дельтаШирота;
      url += `&viewbox=${west},${north},${east},${south}&bounded=1`;
    }
    const відповідь = fetchЗПовтором_(url, {
      headers: { 'User-Agent': 'DorozhniyList-VijskovaLogistyka/1.0 (arsord-logistics)' },
      muteHttpExceptions: true
    }, 2);
    if (відповідь.getResponseCode() !== 200) return null;
    const текст = відповідь.getContentText();
    if (!текст.trim().startsWith('[')) return null;
    const результат = JSON.parse(текст);
    if (!результат.length) return null;
    return { lat: parseFloat(результат[0].lat), lon: parseFloat(результат[0].lon) };
  } catch (e) {
    return null;
  }
}

function отриматиМежіПункту_(назва) {
  try {
    Utilities.sleep(1000);
    const url = 'https://nominatim.openstreetmap.org/search?format=jsonv2&polygon_geojson=1&limit=1&q=' +
      кодуватиURI_(назва + ', Україна');
    const відповідь = fetchЗПовтором_(url, {
      headers: { 'User-Agent': 'DorozhniyList-VijskovaLogistyka/1.0 (arsord-logistics)' },
      muteHttpExceptions: true
    }, 2);

    if (відповідь.getResponseCode() !== 200) return null;
    const текст = відповідь.getContentText();
    if (!текст.trim().startsWith('[')) return null;

    const результат = JSON.parse(текст);
    if (!результат.length || !результат[0].geojson) return null;
    const geojson = результат[0].geojson;
    if (geojson.type === 'Polygon') return [geojson.coordinates];
    if (geojson.type === 'MultiPolygon') return geojson.coordinates;
    return null;
  } catch (e) {
    return null;
  }
}

function додатиНаселенийПункт(назва, категорія, довжинаПроїзду, lat, lon) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.НАСЕЛЕНІ_ПУНКТИ);
  const останнійРядок = аркуш.getLastRow();
  if (останнійРядок > 1) {
    const дані = аркуш.getRange(2, 1, останнійРядок - 1, 1).getValues();
    const індекс = дані.findIndex(р => р[0] && р[0].toString().trim().toLowerCase() === назва.trim().toLowerCase());
    if (індекс !== -1) {
      аркуш.getRange(індекс + 2, 1, 1, 5).setValues([[назва, категорія, Number(довжинаПроїзду), lat, lon]]);
      return { успіх: true };
    }
  }
  аркуш.appendRow([назва, категорія, Number(довжинаПроїзду), lat, lon]);
  return { успіх: true };
}

function знайтиВПерегонах_(пунктА, пунктБ) {
  const повний = знайтиВПерегонахПовне_(пунктА, пунктБ);
  return повний ? повний.км : null;
}

// Повертає і відстань, і геометрію (якщо збережена) — використовується для наочного перегляду,
// щоб показати САМЕ ТОЙ маршрут, який реально порахований і закешований, а не будь-який перший-ліпший.
function знайтиВПерегонахПовне_(пунктА, пунктБ) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.ПЕРЕГОНИ);
  const дані = аркуш.getLastRow() > 1 ? аркуш.getRange(2, 1, аркуш.getLastRow() - 1, 5).getValues() : [];
  const кеш = дані.find(р =>
    (р[0] === пунктА && р[1] === пунктБ) || (р[0] === пунктБ && р[1] === пунктА));
  if (!кеш) return null;
  let geometry = null;
  if (кеш[4]) {
    try { geometry = JSON.parse(кеш[4]); } catch (e) { geometry = null; }
  }
  return { км: кеш[2], geometry: geometry };
}

function зберегтиВПерегони_(пунктА, пунктБ, км, geometry) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.ПЕРЕГОНИ);
  const спрощена = спроститиГеометрію_(geometry);
  try {
    аркуш.appendRow([пунктА, пунктБ, км, new Date(), спрощена ? JSON.stringify(спрощена) : '']);
  } catch (e) {
    // навіть якщо запис геометрії з якоїсь причини не вдався — кілометраж усе одно має зберегтись,
    // а не зірвати весь розрахунок маршруту через проблему, що стосується лише картинки для перегляду
    аркуш.appendRow([пунктА, пунктБ, км, new Date(), '']);
  }
}

// Geometry реального маршруту може мати сотні-тисячі точок — забагато для однієї клітинки
// Google Таблиці (ліміт ~50 000 символів). Для наочного перегляду на карті цього не треба:
// лишаємо не більше ~150 точок (рівномірно розріджуючи), цього достатньо, щоб лінія маршруту
// на карті виглядала так само плавно й точно.
function спроститиГеометрію_(geometry, максТочок) {
  максТочок = максТочок || 150;
  if (!geometry || geometry.length <= максТочок) return geometry;
  const крок = Math.ceil(geometry.length / максТочок);
  const спрощена = [];
  for (let i = 0; i < geometry.length; i += крок) спрощена.push(geometry[i]);
  const остання = geometry[geometry.length - 1];
  if (спрощена[спрощена.length - 1] !== остання) спрощена.push(остання);
  return спрощена;
}

// Явний вибір водієм конкретного варіанту маршруту між двома пунктами — кешується назавжди,
// разом з геометрією САМЕ ЦЬОГО варіанту (щоб перегляд маршруту показував те, що реально обрано,
// а не інший, "типовий" варіант від ORS).
function зберегтиВибранийВідрізок(від, до, км, geometry) {
  видалитиКешПерегонівДляПари_(від, до); // прибираємо стару відповідь (якщо була), щоб не задублювати
  зберегтиВПерегони_(від, до, Number(км), geometry);
  return { успіх: true };
}

// Швидке пакетне видалення: читає весь аркуш ОДИН раз, лишає тільки рядки, що НЕ проходять
// фільтр, і записує назад ОДНИМ setValues (плюс одне очищення хвоста, якщо стало менше рядків).
// Це значно швидше за deleteRow() у циклі — Google Sheets перебудовує індекси/формули при
// кожному окремому deleteRow, а тут перебудова відбувається рівно один раз.
function видалитиРядкиЗаФільтром_(назваАркуша, предикатВидалити) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(назваАркуша);
  const останнійРядок = аркуш.getLastRow();
  if (останнійРядок < 2) return;
  const колонок = аркуш.getLastColumn();
  const дані = аркуш.getRange(2, 1, останнійРядок - 1, колонок).getValues();
  const залишити = дані.filter(р => !предикатВидалити(р));
  if (залишити.length === дані.length) return; // нічого не змінилось

  if (залишити.length > 0) {
    аркуш.getRange(2, 1, залишити.length, колонок).setValues(залишити);
  }
  const хвостВідРядка = 2 + залишити.length;
  const хвостДовжина = останнійРядок - хвостВідРядка + 1;
  if (хвостДовжина > 0) {
    аркуш.getRange(хвостВідРядка, 1, хвостДовжина, колонок).clearContent();
  }
}

function видалитиКешПерегонівДляПари_(пунктА, пунктБ) {
  видалитиРядкиЗаФільтром_(АРКУШІ.ПЕРЕГОНИ, р => (р[0] === пунктА && р[1] === пунктБ) || (р[0] === пунктБ && р[1] === пунктА));
}

// Виправлення координат уже класифікованого пункту (наприклад, коли ORS не може прокласти
// маршрут через нього — водій сам ставить точку на карті ближче до реальної дороги).
// Повертає поточні координати вже відомого населеного пункту (для покрокового редагування точок маршруту)
// Повертає геометрію вже класифікованого маршруту — бере ЗАКЕШОВАНУ геометрію того самого варіанту,
// що реально порахований і збережений (не робить новий довільний запит до ORS, який міг би повернути
// зовсім інший маршрут). Якщо геометрія з якоїсь причини не збереглась (старі записи до цього фіксу) —
// тоді вже підвантажує заново як запасний варіант.
function отриматиГеометріюМаршруту(пункти) {
  const сегменти = [];
  let усього = 0;
  for (let i = 0; i < пункти.length - 1; i++) {
    const а = пункти[i].trim();
    const б = пункти[i + 1].trim();
    const коорА = отриматиКоординати_(а, null);
    const коорБ = отриматиКоординати_(б, null);
    if (коорА.нове || коорБ.нове) {
      throw new Error(`Пункт "${коорА.нове ? а : б}" ще не класифікований — спочатку натисни 🧮, щоб порахувати маршрут.`);
    }

    const закешоване = знайтиВПерегонахПовне_(а, б);
    let км, geometry;
    if (закешоване && закешоване.geometry) {
      км = закешоване.км;
      geometry = закешоване.geometry;
    } else {
      const варіанти = отриматиМаршрутORS_(коорА, коорБ, false);
      км = закешоване ? закешоване.км : варіанти[0].км; // якщо є закешована відстань — довіряємо їй, а не новому запиту
      geometry = варіанти[0].geometry;
    }

    усього += км;
    сегменти.push({
      від: а, до: б, км: км, geometry: geometry,
      точкаА: { lat: коорА.lat, lon: коорА.lon }, точкаБ: { lat: коорБ.lat, lon: коорБ.lon }
    });
  }
  return { сегменти: сегменти, усього: Math.round(усього * 10) / 10 };
}

// Віддає вже закешовану (можливо, вручну скориговану) ділянку між двома пунктами, якщо вона є —
// використовується інструментом ручного коригування, щоб при повторному відкритті показати САМЕ
// ТОЙ маршрут, що реально збережений, а не заново запитаний у ORS "типовий" варіант.
function отриматиЗбереженуДілянку(від, до) {
  const закешоване = знайтиВПерегонахПовне_(від, до);
  if (!закешоване || !закешоване.geometry) return { знайдено: false };
  return { знайдено: true, км: закешоване.км, geometry: закешоване.geometry };
}

function отриматиНаселенийПункт(назва) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.НАСЕЛЕНІ_ПУНКТИ);
  if (аркуш.getLastRow() < 2) return { знайдено: false };
  const дані = аркуш.getRange(2, 1, аркуш.getLastRow() - 1, 5).getValues();
  const рядок = дані.find(р => р[0] && р[0].toString().trim().toLowerCase() === назва.trim().toLowerCase());
  if (!рядок || !рядок[3] || !рядок[4]) return { знайдено: false };
  return { знайдено: true, lat: рядок[3], lon: рядок[4], категорія: рядок[1], довжинаПроїзду: рядок[2] };
}

function оновитиКоординатиПункту(назва, lat, lon) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.НАСЕЛЕНІ_ПУНКТИ);
  const останнійРядок = аркуш.getLastRow();
  if (останнійРядок > 1) {
    const дані = аркуш.getRange(2, 1, останнійРядок - 1, 1).getValues();
    const індекс = дані.findIndex(р => р[0] && р[0].toString().trim().toLowerCase() === назва.trim().toLowerCase());
    if (індекс !== -1) {
      аркуш.getRange(індекс + 2, 4, 1, 2).setValues([[lat, lon]]); // лише координати, категорію не чіпаємо
      видалитиКешПерегонівДляПункту_(назва);
      return { успіх: true };
    }
  }
  // пункту ще немає в довіднику взагалі (виправлення сталось до першої класифікації) —
  // створюємо частковий запис із координатами, категорію спитаємо на наступному кроці як завжди
  аркуш.appendRow([назва, '', '', lat, lon]);
  видалитиКешПерегонівДляПункту_(назва);
  return { успіх: true };
}

// Координати пункту змінились — усі раніше пораховані й закешовані відстані до/від нього
// вже недійсні. Видаляємо їх з "Перегони", щоб наступний розрахунок пішов заново через ORS,
// а не мовчки взяв старе число, пораховане для старої точки.
function видалитиКешПерегонівДляПункту_(назва) {
  const назваНижнім = назва.trim().toLowerCase();
  видалитиРядкиЗаФільтром_(АРКУШІ.ПЕРЕГОНИ, р =>
    String(р[0]).trim().toLowerCase() === назваНижнім || String(р[1]).trim().toLowerCase() === назваНижнім);
}

function отриматиВідстань_(пунктА, пунктБ, координатиА, координатиБ) {
  const кеш = знайтиВПерегонах_(пунктА, пунктБ);
  if (кеш != null) return кеш;

  const варіанти = отриматиМаршрутORS_(координатиА, координатиБ, true);
  const обраний = варіанти.reduce((найкращий, поточний) => поточний.км < найкращий.км ? поточний : найкращий);
  зберегтиВПерегони_(пунктА, пунктБ, обраний.км, обраний.geometry);
  return обраний.км;
}

function отриматиВідстаньІГеометрію_(пунктА, пунктБ, координатиА, координатиБ) {
  const варіанти = отриматиМаршрутORS_(координатиА, координатиБ, false);
  return варіанти[0];
}

// зГеометрією тут завжди повертається (потрібна і для одного маршруту, і для порівняння варіантів)
// Відстань і геометрія між двома довільними координатами (не обов'язково класифікованими населеними
// пунктами) — потрібна для ручного коригування маршруту (проміжні точки, які водій сам ставить на карті).
function отриматиВідстаньМіжКоординатами(координатиА, координатиБ) {
  const варіанти = отриматиМаршрутORS_(координатиА, координатиБ, false);
  return { км: варіанти[0].км, geometry: варіанти[0].geometry };
}

function отриматиМаршрутORS_(координатиА, координатиБ, шукатиАльтернативи) {
  const ключ = отриматиORSКлюч_();
  const url = 'https://api.openrouteservice.org/v2/directions/driving-car/geojson';
  const тіло = { coordinates: [[координатиА.lon, координатиА.lat], [координатиБ.lon, координатиБ.lat]] };
  // Типовий радіус прив'язки точки до дороги в ORS — 350м, цього часто замало для сіл/хуторів
  // з рідкою дорожньою мережею на карті. Розширюємо до 2 км на кожну точку.
  тіло.radiuses = [2000, 2000];
  if (шукатиАльтернативи) {
    тіло.alternative_routes = { target_count: 3, weight_factor: 1.6, share_factor: 0.6 };
  }
  const відповідь = fetchЗПовтором_(url, {
    method: 'post',
    contentType: 'application/json',
    headers: { 'Authorization': ключ },
    payload: JSON.stringify(тіло),
    muteHttpExceptions: true
  });

  const код = відповідь.getResponseCode();
  const текстВідповіді = відповідь.getContentText();
  if (код !== 200) {
    // ORS не може прив'язати одну з точок до дорожньої мережі (наприклад, вона потрапила в поле чи водойму)
    if (текстВідповіді.includes('"code":2010')) {
      const збіг = текстВідповіді.match(/coordinate (\d+): ([\d.]+) ([\d.]+)/);
      if (збіг) {
        const е = new Error('НЕПРОЇЗНА_ТОЧКА');
        е.координата = { lon: Number(збіг[2]), lat: Number(збіг[3]) };
        throw е;
      }
    }
    // ORS не рахує альтернативні маршрути (порівняння варіантів) для відрізків довших за 100 км
    // — це ліміт самого сервера ORS (code 2004), не наша помилка. Для таких далеких пунктів
    // (напр. обласний центр) просто рахуємо ОДИН (найкращий) маршрут без порівняння варіантів.
    if (шукатиАльтернативи && текстВідповіді.includes('"code":2004')) {
      return отриматиМаршрутORS_(координатиА, координатиБ, false);
    }
    throw new Error(`OpenRouteService (маршрутизація) відповів кодом ${код}. Можна вписати відстань вручну ` +
      `в аркуш "Перегони" (колонка "Відстань (км)") і спробувати ще раз. Деталі: ${текстВідповіді.substring(0, 200)}`);
  }

  const результат = JSON.parse(текстВідповіді);
  if (!результат.features || !результат.features.length) throw new Error('Не вдалося розрахувати маршрут між точками');

  return результат.features.map(f => ({
    км: Math.round(f.properties.summary.distance / 100) / 10,
    geometry: f.geometry.coordinates
  }));
}

function точкаВПолігоні_(лон, лат, мультиполігон) {
  for (const полігон of мультиполігон) {
    let всередині = false;
    for (const кільце of полігон) {
      for (let i = 0, j = кільце.length - 1; i < кільце.length; j = i++) {
        const xi = кільце[i][0], yi = кільце[i][1];
        const xj = кільце[j][0], yj = кільце[j][1];
        const перетин = ((yi > лат) !== (yj > лат)) &&
          (лон < (xj - xi) * (лат - yi) / (yj - yi) + xi);
        if (перетин) всередині = !всередині;
      }
    }
    if (всередині) return true;
  }
  return false;
}

function haversine_(lat1, lon1, lat2, lon2) {
  const R = 6371;
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLon = (lon2 - lon1) * Math.PI / 180;
  const a = Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1 * Math.PI / 180) * Math.cos(lat2 * Math.PI / 180) * Math.sin(dLon / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

function обчислитиДовжинуВМежах_(geometry, мультиполігон) {
  if (!мультиполігон || !geometry) return null;
  let довжина = 0;
  for (let i = 0; i < geometry.length - 1; i++) {
    const [lon1, lat1] = geometry[i];
    const [lon2, lat2] = geometry[i + 1];
    const серЛон = (lon1 + lon2) / 2, серЛат = (lat1 + lat2) / 2;
    if (точкаВПолігоні_(серЛон, серЛат, мультиполігон)) {
      довжина += haversine_(lat1, lon1, lat2, lon2);
    }
  }
  return Math.round(довжина * 10) / 10;
}

// ==================== РОЗРАХУНОК МАРШРУТУ ====================
function розрахуватиМаршрут(пункти) {
  const нові = [];
  const сегменти = [];

  let попередніКоор = null; // координати останньої вже відомої точки маршруту — біас для геокодування далі

  for (let i = 0; i < пункти.length - 1; i++) {
    const а = пункти[i].trim();
    const б = пункти[i + 1].trim();

    let коорА, коорБ;
    try {
      коорА = отриматиКоординати_(а, попередніКоор);
    } catch (е) {
      if (е.message === 'НЕ_ЗНАЙДЕНО_РУЧНЕ_РОЗМІЩЕННЯ') {
        return {
          потрібнаКласифікація: false, потрібенВибірМаршруту: false, потрібнеВиправленняТочки: false,
          потрібнеРучнеРозміщенняПункту: true,
          пункт: { назва: а, lat: е.приблизнаКоор.lat, lon: е.приблизнаКоор.lon }
        };
      }
      throw е;
    }
    попередніКоор = { lat: коорА.lat, lon: коорА.lon };
    try {
      коорБ = отриматиКоординати_(б, попередніКоор);
    } catch (е) {
      if (е.message === 'НЕ_ЗНАЙДЕНО_РУЧНЕ_РОЗМІЩЕННЯ') {
        return {
          потрібнаКласифікація: false, потрібенВибірМаршруту: false, потрібнеВиправленняТочки: false,
          потрібнеРучнеРозміщенняПункту: true,
          пункт: { назва: б, lat: е.приблизнаКоор.lat, lon: е.приблизнаКоор.lon }
        };
      }
      throw е;
    }
    попередніКоор = { lat: коорБ.lat, lon: коорБ.lon };

    if (коорА.нове || коорБ.нове) {
      let геом;
      try {
        геом = отриматиВідстаньІГеометрію_(а, б, коорА, коорБ);
      } catch (е) {
        if (е.message === 'НЕПРОЇЗНА_ТОЧКА' && е.координата) {
          const відДоА = haversine_(е.координата.lat, е.координата.lon, коорА.lat, коорА.lon);
          const відДоБ = haversine_(е.координата.lat, е.координата.lon, коорБ.lat, коорБ.lon);
          const винний = відДоА <= відДоБ ? { назва: а, lat: коорА.lat, lon: коорА.lon } : { назва: б, lat: коорБ.lat, lon: коорБ.lon };
          return { потрібнаКласифікація: false, потрібенВибірМаршруту: false, потрібнеВиправленняТочки: true, пункт: винний };
        }
        throw е;
      }
      if (коорА.нове && !нові.find(п => п.назва === а)) {
        нові.push({
          назва: а, lat: коорА.lat, lon: коорА.lon,
          довжинаАвто: обчислитиДовжинуВМежах_(геом.geometry, коорА.межі)
        });
      }
      if (коорБ.нове && !нові.find(п => п.назва === б)) {
        нові.push({
          назва: б, lat: коорБ.lat, lon: коорБ.lon,
          довжинаАвто: обчислитиДовжинуВМежах_(геом.geometry, коорБ.межі)
        });
      }
      continue;
    }

    // Обидва пункти вже відомі. Якщо перегін ще не кешовано — перевіряємо альтернативні маршрути,
    // і якщо вони суттєво відрізняються, зупиняємось і просимо водія обрати (замість мовчки брати найкоротший).
    const кеш = знайтиВПерегонах_(а, б);
    let відстань;
    if (кеш != null) {
      відстань = кеш;
    } else {
      let варіанти;
      try {
        варіанти = отриматиМаршрутORS_(коорА, коорБ, true);
      } catch (е) {
        if (е.message === 'НЕПРОЇЗНА_ТОЧКА' && е.координата) {
          const відДоА = haversine_(е.координата.lat, е.координата.lon, коорА.lat, коорА.lon);
          const відДоБ = haversine_(е.координата.lat, е.координата.lon, коорБ.lat, коорБ.lon);
          const винний = відДоА <= відДоБ ? { назва: а, lat: коорА.lat, lon: коорА.lon } : { назва: б, lat: коорБ.lat, lon: коорБ.lon };
          return { потрібнаКласифікація: false, потрібенВибірМаршруту: false, потрібнеВиправленняТочки: true, пункт: винний };
        }
        throw е;
      }
      if (варіанти.length > 1) {
        const кмСписок = варіанти.map(v => v.км);
        const мін = Math.min(...кмСписок), макс = Math.max(...кмСписок);
        const суттєваРізниця = (макс - мін) >= 5 && (макс - мін) / мін >= 0.10;
        if (суттєваРізниця) {
          return {
            потрібнаКласифікація: false,
            потрібенВибірМаршруту: true,
            відрізок: { від: а, до: б },
            варіанти: варіанти.map((v, idx) => ({ індекс: idx, км: v.км, geometry: v.geometry })),
            центр: { lat: (коорА.lat + коорБ.lat) / 2, lon: (коорА.lon + коорБ.lon) / 2 }
          };
        }
      }
      const обраний = варіанти.reduce((найкращий, поточний) => поточний.км < найкращий.км ? поточний : найкращий);
      зберегтиВПерегони_(а, б, обраний.км, обраний.geometry);
      відстань = обраний.км;
    }

    const довжинаА = коорА.довжинаПроїзду || 0;
    const довжинаБ = коорБ.довжинаПроїзду || 0;
    const траса = Math.max(0, відстань - довжинаА - довжинаБ);

    сегменти.push({
      від: а, до: б, всього: відстань, траса: траса,
      пункти: [
        { назва: а, категорія: коорА.категорія, км: довжинаА },
        { назва: б, категорія: коорБ.категорія, км: довжинаБ }
      ]
    });
  }

  if (нові.length) {
    return { потрібнаКласифікація: true, нові: нові };
  }

  return { потрібнаКласифікація: false, сегменти: сегменти, підсумок: підсумуватиСегменти_(сегменти) };
}

function підсумуватиСегменти_(сегменти) {
  const підсумок = {
    всього: 0, 'Траса': 0,
    'Населений пункт без регульованих перехресть': 0,
    'Місто з регульованими перехрестями': 0,
    'Обласний центр': 0
  };
  сегменти.forEach(с => {
    підсумок.всього += с.всього;
    підсумок['Траса'] += с.траса;
    с.пункти.forEach(п => {
      if (п.категорія) підсумок[п.категорія] += п.км;
    });
  });
  return підсумок;
}

// ==================== РОЗРАХУНОК НОРМИ ПММ ====================
function розрахуватиНормуПММ(підсумокКм, нормаНа100км) {
  let потрібно = 0;
  Object.keys(КОЕФІЦІЄНТИ_ДІЛЯНОК).forEach(тип => {
    const км = підсумокКм[тип] || 0;
    потрібно += (км / 100) * нормаНа100км * КОЕФІЦІЄНТИ_ДІЛЯНОК[тип];
  });
  return Math.round(потрібно * 100) / 100;
}

