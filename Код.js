function fetchЗПовтором_(url, опції, макс) {
  макс = макс || 4;
  let відповідь;
  for (let спроба = 1; спроба <= макс; спроба++) {
    відповідь = UrlFetchApp.fetch(url, опції);
    if (відповідь.getResponseCode() !== 429) return відповідь;
    if (спроба < макс) Utilities.sleep(1500 * спроба); // 1.5с, 3с, 4.5с...
  }
  return відповідь;
}

