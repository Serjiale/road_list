    номер: рядокЛиста[0], дата: рядокЛиста[1], дійснийДо: рядокЛиста[2],
    держНомер: рядокЛиста[3], водій: рядокЛиста[4], підстава: рядокЛиста[5],
    статус: рядокЛиста[6], одометр: рядокЛиста[7],
    частина: рядокЛиста[9], старшийМашини: рядокЛиста[10], начальник: рядокЛиста[11],
