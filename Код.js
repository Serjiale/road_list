const ТИПИ_ПММ_НАЗВА_ = { 'паливо': 'палива', 'adblue': 'AdBlue', 'олива': 'оливи' };

function отриматиНормуМашиниЗаТипом_(держНомер, тип) {
  const ss = SpreadsheetApp.getActiveSpreadsheet();
  const аркуш = ss.getSheetByName(АРКУШІ.МАШИНИ);
  const дані = аркуш.getRange(2, 1, аркуш.getLastRow() - 1, 7).getValues();
  const машина = дані.find(р => String(р[0]).trim() === String(держНомер).trim());
  if (!машина) throw new Error('Машину ' + держНомер + ' не знайдено в довіднику "Машини"');

  const колонка = тип === 'adblue' ? 4 : (тип === 'олива' ? 5 : 3); // паливо — за замовчуванням
  const норма = Number(машина[колонка]);
  if (машина[колонка] === '' || isNaN(норма)) {
    throw new Error(
      `У машини ${держНомер} не вказана (або не число) норма ${ТИПИ_ПММ_НАЗВА_[тип] || тип} у довіднику "Машини". ` +
      `Заповни відповідну колонку числом і спробуй ще раз.`
    );
  }
  return норма;
}

// Розраховує "Витрачено" за кілометражем поїздок листа (з коефіцієнтами ділянок) і нормою машини —
// ОКРЕМО для кожного ТИПУ ПММ (паливо/AdBlue/олива), незалежно від того, скількома рядками з
// різними найменуваннями цей тип записаний. Витрата списується послідовно зверху вниз: спершу
// вичерпується "наявність перед виїздом" і "отримано" найвищого рядка цього типу, тоді автоматично
// переходить до наступного рядка того самого типу — і так, поки не покриє всю потребу або не
// закінчаться рядки (тоді перевитрата, вже по типу в цілому, а не по окремому рядку).
// рядки: [{id?, найменування, тип, код, наявністьПеред, отримано, належить}]
function розрахуватиТаЗберегтиПММЛиста(номерЛиста, рядки, користувач) {
  перевіритиДоступДоЛиста_(користувач, номерЛиста);
  const держНомер = отриматиДержНомерЛиста(номерЛиста);
  if (!держНомер) throw new Error('Дорожній лист не знайдено');

  const підсумокКм = отриматиПідсумокКмДляЛиста(номерЛиста, користувач);

  рядки.forEach(рядок => {
    if (!рядок.тип) {
      throw new Error(`Не вказано тип для "${рядок.найменування}" — обери паливо/AdBlue/олива в полі назви.`);
    }
  });

  // Групуємо за типом, зберігаючи порядок рядків так, як їх ввів водій (зверху вниз) —
  // саме в цьому порядку йде списання.
  const типиПорядок = [];
  const групиПоТипу = {};
  рядки.forEach((рядок, індексОригінальний) => {
    if (!групиПоТипу[рядок.тип]) { групиПоТипу[рядок.тип] = []; типиПорядок.push(рядок.тип); }
    групиПоТипу[рядок.тип].push({ рядок, індексОригінальний });
  });

  const розраховані = new Array(рядки.length);
  типиПорядок.forEach(тип => {
    const група = групиПоТипу[тип];
    const норма = отриматиНормуМашиниЗаТипом_(держНомер, тип);
    const потрібноВсього = розрахуватиНормуПММ(підсумокКм, норма);
    const наявноВсього = група.reduce((сума, з) => сума + Number(з.рядок.наявністьПеред || 0) + Number(з.рядок.отримано || 0), 0);

    if (потрібноВсього > наявноВсього) {
      const назви = група.map(з => `"${з.рядок.найменування}"`).join(', ');
      throw new Error(
        `Перевитрата ${ТИПИ_ПММ_НАЗВА_[тип] || тип} (${назви}): наявно ${наявноВсього.toFixed(1)} л, а за маршрутом ` +
        `(${підсумокКм.всього.toFixed(1)} км) витрачено б ${потрібноВсього.toFixed(1)} л. ` +
        `Не вистачає ${(потрібноВсього - наявноВсього).toFixed(1)} л. Перевір цифри перед збереженням.`
      );
    }

    let залишокПотреби = потрібноВсього;
    група.forEach(з => {
      const наявно = Number(з.рядок.наявністьПеред || 0) + Number(з.рядок.отримано || 0);
      const витрачено = Math.min(наявно, залишокПотреби);
      залишокПотреби -= витрачено;
      const наявністьНаСтоянці = Math.round((наявно - витрачено) * 100) / 100;
      розраховані[з.індексОригінальний] = { рядок: з.рядок, витрачено: витрачено, наявністьНаСтоянці: наявністьНаСтоянці };
    });
  });

  // "Наявність на стоянці" = 0 означає, що цієї позиції вже немає в баку — лишаємо клітинку
  // порожньою (а не "0"), так само, як лишили б порожньою в паперовому бланку.
  const збережені = розраховані.map(р => зберегтиПММЗапис({
    id: р.рядок.id, номерЛиста: номерЛиста, найменування: р.рядок.найменування, тип: р.рядок.тип,
    код: р.рядок.код, наявністьПеред: р.рядок.наявністьПеред, отримано: р.рядок.отримано,
    стоянка: р.наявністьНаСтоянці > 0 ? р.наявністьНаСтоянці : '', витрачено: Math.round(р.витрачено * 100) / 100,
    належить: р.рядок.належить, економія: '', перевитрата: ''
  }, користувач));

  return {
    успіх: true,
    підсумокКм: підсумокКм,
    результати: розраховані.map((р, i) => ({
      id: збережені[i].id, витрачено: р.витрачено, наявністьНаСтоянці: р.наявністьНаСтоянці
    }))
  };
}

